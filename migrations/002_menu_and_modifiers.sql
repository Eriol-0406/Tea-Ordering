-- OTea x GreyOne - editable menu and modifiers
--
-- Moves the menu out of server.js so staff can change it without a deploy, and
-- makes modifiers real records instead of hardcoded conditionals. This is also
-- the foundation for two later features:
--   * company attribution hangs off the category (line-item revenue split)
--   * recipes will hang off menu items (ingredient depletion)
--
-- Safe to re-run.

-- ---------------------------------------------------------------
-- Companies. Revenue splits by line item via the item's category.
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS companies (
  id   SMALLINT PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL
);

